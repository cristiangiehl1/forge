import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const DIR = process.argv[2]
const OUT = new URL(
  '../apps/web/src/lib/example/recruitment-sql.ts',
  import.meta.url
)
if (!DIR) {
  throw new Error(
    'Usage: node scripts/build-recruitment-example.mjs <migrations dir>'
  )
}

const files = readdirSync(DIR)
  .filter((name) => /^00\d\d_.*\.sql$/.test(name))
  .sort()
const sql = files
  .map((name) => readFileSync(join(DIR, name), 'utf8').trimEnd())
  .join('\n\n')
const header = `// Generated by scripts/build-recruitment-example.mjs from ${files.length} DDL migrations of the\n// recruitment system (Oracle). Do not edit by hand.\n`
writeFileSync(
  OUT,
  `${header}export const RECRUITMENT_SQL = ${JSON.stringify(sql)}\n`
)
console.log(`${files.length} files, ${sql.length} characters`)
